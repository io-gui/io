import {
  BufferGeometry,
  Color,
  DoubleSide,
  ExtrudeGeometry,
  ExtrudeGeometryOptions,
  Group,
  InstancedBufferAttribute,
  Line,
  LineBasicMaterial,
  Mesh,
  MeshPhongMaterial,
  Path,
  PointLight,
  Points,
  PointsMaterial,
  PointsNodeMaterial,
  RepeatWrapping,
  Shape,
  ShapeGeometry,
  SRGBColorSpace,
  Sprite,
  TextureLoader,
  Vector2
} from 'three/webgpu'
import { instancedBufferAttribute } from 'three/tsl'
import { Register } from '@io-gui/core'
import { Document, DocumentProps } from '@io-gui/three'

/**
 * Eleven 2D shapes (California, a heart, a smiley with holes, ...), each drawn seven ways from back to front: a
 * `ShapeGeometry` with a uv grid, a flat one, an extrusion, its outline as a line, a line through equally spaced
 * points, and both point sets. WebGPU draws `Points` 1 px wide, so each point set has a child `Sprite` that draws its
 * dots at the source's size. The camera's light is a point light at the source camera's position; the pointer drag that
 * turned the group is dropped. Static.
 */
@Register
export class GeometryShapesExample extends Document {

  constructor(args?: DocumentProps) {
    super(args)

    this.scene.background = new Color( 0xf0f0f0 )

    // The source attaches its light to the camera at (0, 150, 500).
    const light = new PointLight( 0xffffff, 2.5, 0, 0 )
    light.name = 'Camera Light'
    light.position.set( 0, 150, 500 )
    this.scene.add( light )

    const group = new Group()
    group.name = 'Shapes'
    group.position.y = 50
    this.scene.add( group )

    const loader = new TextureLoader()
    // Views draw on document changes only, so report the texture when it arrives.
    const texture = loader.load( 'https://threejs.org/examples/textures/uv_grid_opengl.jpg', () => this.notify({kind: 'material'}) )
    texture.colorSpace = SRGBColorSpace

    // it's necessary to apply these settings in order to correctly display the texture on a shape geometry

    texture.wrapS = texture.wrapT = RepeatWrapping
    texture.repeat.set( 0.008, 0.008 )

    const place = ( object: Mesh | Line | Points, x: number, y: number, z: number, rx: number, ry: number, rz: number, s: number ) => {
      object.position.set( x, y, z )
      object.rotation.set( rx, ry, rz )
      object.scale.set( s, s, s )
    }

    const addShape = ( name: string, shape: Shape, extrudeSettings: ExtrudeGeometryOptions, color: number, x: number, y: number, z: number, rx: number, ry: number, rz: number, s: number ) => {

      const parent = new Group()
      parent.name = name
      group.add( parent )

      // flat shape with texture
      // note: default UVs generated by ShapeGeometry are simply the x- and y-coordinates of the vertices

      let geometry: BufferGeometry = new ShapeGeometry( shape )

      let mesh = new Mesh( geometry, new MeshPhongMaterial( { side: DoubleSide, map: texture } ) )
      mesh.name = 'Textured'
      place( mesh, x, y, z - 175, rx, ry, rz, s )
      parent.add( mesh )

      // flat shape

      geometry = new ShapeGeometry( shape )

      mesh = new Mesh( geometry, new MeshPhongMaterial( { color: color, side: DoubleSide } ) )
      mesh.name = 'Flat'
      place( mesh, x, y, z - 125, rx, ry, rz, s )
      parent.add( mesh )

      // extruded shape

      geometry = new ExtrudeGeometry( shape, extrudeSettings )

      mesh = new Mesh( geometry, new MeshPhongMaterial( { color: color } ) )
      mesh.name = 'Extruded'
      place( mesh, x, y, z - 75, rx, ry, rz, s )
      parent.add( mesh )

      addLineShape( parent, shape, color, x, y, z, rx, ry, rz, s )

    }

    const addLineShape = ( parent: Group, shape: Path, color: number, x: number, y: number, z: number, rx: number, ry: number, rz: number, s: number ) => {

      // lines

      shape.autoClose = true

      const points = shape.getPoints()
      const spacedPoints = shape.getSpacedPoints( 50 )

      const geometryPoints = new BufferGeometry().setFromPoints( points )
      const geometrySpacedPoints = new BufferGeometry().setFromPoints( spacedPoints )

      // solid line

      let line = new Line( geometryPoints, new LineBasicMaterial( { color: color } ) )
      line.name = 'Line'
      place( line, x, y, z - 25, rx, ry, rz, s )
      parent.add( line )

      // line from equidistance sampled points

      line = new Line( geometrySpacedPoints, new LineBasicMaterial( { color: color } ) )
      line.name = 'Spaced Line'
      place( line, x, y, z + 25, rx, ry, rz, s )
      parent.add( line )

      // vertices from real points

      let particles = new Points( geometryPoints, new PointsMaterial( { color: color, size: 4 } ) )
      particles.name = 'Points'
      particles.add( createSprites( particles ) )
      place( particles, x, y, z + 75, rx, ry, rz, s )
      parent.add( particles )

      // equidistance sampled points

      particles = new Points( geometrySpacedPoints, new PointsMaterial( { color: color, size: 4 } ) )
      particles.name = 'Spaced Points'
      particles.add( createSprites( particles ) )
      place( particles, x, y, z + 125, rx, ry, rz, s )
      parent.add( particles )

      return parent

    }

    // California

    const californiaPts: Vector2[] = []

    californiaPts.push( new Vector2( 610, 320 ) )
    californiaPts.push( new Vector2( 450, 300 ) )
    californiaPts.push( new Vector2( 392, 392 ) )
    californiaPts.push( new Vector2( 266, 438 ) )
    californiaPts.push( new Vector2( 190, 570 ) )
    californiaPts.push( new Vector2( 190, 600 ) )
    californiaPts.push( new Vector2( 160, 620 ) )
    californiaPts.push( new Vector2( 160, 650 ) )
    californiaPts.push( new Vector2( 180, 640 ) )
    californiaPts.push( new Vector2( 165, 680 ) )
    californiaPts.push( new Vector2( 150, 670 ) )
    californiaPts.push( new Vector2( 90, 737 ) )
    californiaPts.push( new Vector2( 80, 795 ) )
    californiaPts.push( new Vector2( 50, 835 ) )
    californiaPts.push( new Vector2( 64, 870 ) )
    californiaPts.push( new Vector2( 60, 945 ) )
    californiaPts.push( new Vector2( 300, 945 ) )
    californiaPts.push( new Vector2( 300, 743 ) )
    californiaPts.push( new Vector2( 600, 473 ) )
    californiaPts.push( new Vector2( 626, 425 ) )
    californiaPts.push( new Vector2( 600, 370 ) )
    californiaPts.push( new Vector2( 610, 320 ) )

    for ( let i = 0; i < californiaPts.length; i ++ ) californiaPts[ i ].multiplyScalar( 0.25 )

    const californiaShape = new Shape( californiaPts )

    // Triangle

    const triangleShape = new Shape()
      .moveTo( 80, 20 )
      .lineTo( 40, 80 )
      .lineTo( 120, 80 )
      .lineTo( 80, 20 ) // close path

    // Heart

    const x = 0, y = 0

    const heartShape = new Shape()
      .moveTo( x + 25, y + 25 )
      .bezierCurveTo( x + 25, y + 25, x + 20, y, x, y )
      .bezierCurveTo( x - 30, y, x - 30, y + 35, x - 30, y + 35 )
      .bezierCurveTo( x - 30, y + 55, x - 10, y + 77, x + 25, y + 95 )
      .bezierCurveTo( x + 60, y + 77, x + 80, y + 55, x + 80, y + 35 )
      .bezierCurveTo( x + 80, y + 35, x + 80, y, x + 50, y )
      .bezierCurveTo( x + 35, y, x + 25, y + 25, x + 25, y + 25 )

    // Square

    const sqLength = 80

    const squareShape = new Shape()
      .moveTo( 0, 0 )
      .lineTo( 0, sqLength )
      .lineTo( sqLength, sqLength )
      .lineTo( sqLength, 0 )
      .lineTo( 0, 0 )

    // Rounded rectangle

    const roundedRectShape = new Shape();

    ( function roundedRect( ctx: Shape, x: number, y: number, width: number, height: number, radius: number ) {

      ctx.moveTo( x, y + radius )
      ctx.lineTo( x, y + height - radius )
      ctx.quadraticCurveTo( x, y + height, x + radius, y + height )
      ctx.lineTo( x + width - radius, y + height )
      ctx.quadraticCurveTo( x + width, y + height, x + width, y + height - radius )
      ctx.lineTo( x + width, y + radius )
      ctx.quadraticCurveTo( x + width, y, x + width - radius, y )
      ctx.lineTo( x + radius, y )
      ctx.quadraticCurveTo( x, y, x, y + radius )

    } )( roundedRectShape, 0, 0, 50, 50, 20 )

    // Track

    const trackShape = new Shape()
      .moveTo( 40, 40 )
      .lineTo( 40, 160 )
      .absarc( 60, 160, 20, Math.PI, 0, true )
      .lineTo( 80, 40 )
      .absarc( 60, 40, 20, 2 * Math.PI, Math.PI, true )

    // Circle

    const circleRadius = 40
    const circleShape = new Shape()
      .moveTo( 0, circleRadius )
      .quadraticCurveTo( circleRadius, circleRadius, circleRadius, 0 )
      .quadraticCurveTo( circleRadius, - circleRadius, 0, - circleRadius )
      .quadraticCurveTo( - circleRadius, - circleRadius, - circleRadius, 0 )
      .quadraticCurveTo( - circleRadius, circleRadius, 0, circleRadius )

    // Fish

    const fishShape = new Shape()
      .moveTo( x, y )
      .quadraticCurveTo( x + 50, y - 80, x + 90, y - 10 )
      .quadraticCurveTo( x + 100, y - 10, x + 115, y - 40 )
      .quadraticCurveTo( x + 115, y, x + 115, y + 40 )
      .quadraticCurveTo( x + 100, y + 10, x + 90, y + 10 )
      .quadraticCurveTo( x + 50, y + 80, x, y )

    // Arc circle

    const arcShape = new Shape()
      .moveTo( 50, 10 )
      .absarc( 10, 10, 40, 0, Math.PI * 2, false )

    const holePath = new Path()
      .moveTo( 20, 10 )
      .absarc( 10, 10, 10, 0, Math.PI * 2, true )

    arcShape.holes.push( holePath )

    // Smiley

    const smileyShape = new Shape()
      .moveTo( 80, 40 )
      .absarc( 40, 40, 40, 0, Math.PI * 2, false )

    const smileyEye1Path = new Path()
      .moveTo( 35, 20 )
      .absellipse( 25, 20, 10, 10, 0, Math.PI * 2, true, 0 )

    const smileyEye2Path = new Path()
      .moveTo( 65, 20 )
      .absarc( 55, 20, 10, 0, Math.PI * 2, true )

    const smileyMouthPath = new Path()
      .moveTo( 20, 40 )
      .quadraticCurveTo( 40, 60, 60, 40 )
      .bezierCurveTo( 70, 45, 70, 50, 60, 60 )
      .quadraticCurveTo( 40, 80, 20, 60 )
      .quadraticCurveTo( 5, 50, 20, 40 )

    smileyShape.holes.push( smileyEye1Path )
    smileyShape.holes.push( smileyEye2Path )
    smileyShape.holes.push( smileyMouthPath )

    // Spline shape

    const splinepts: Vector2[] = []
    splinepts.push( new Vector2( 70, 20 ) )
    splinepts.push( new Vector2( 80, 90 ) )
    splinepts.push( new Vector2( - 30, 70 ) )
    splinepts.push( new Vector2( 0, 0 ) )

    const splineShape = new Shape()
      .moveTo( 0, 0 )
      .splineThru( splinepts )

    const extrudeSettings = { depth: 8, bevelEnabled: true, bevelSegments: 2, steps: 2, bevelSize: 1, bevelThickness: 1 }

    // addShape( shape, color, x, y, z, rx, ry,rz, s );

    addShape( 'California', californiaShape, extrudeSettings, 0xf08000, - 300, - 100, 0, 0, 0, 0, 1 )
    addShape( 'Triangle', triangleShape, extrudeSettings, 0x8080f0, - 180, 0, 0, 0, 0, 0, 1 )
    addShape( 'Rounded Rectangle', roundedRectShape, extrudeSettings, 0x008000, - 150, 150, 0, 0, 0, 0, 1 )
    addShape( 'Track', trackShape, extrudeSettings, 0x008080, 200, - 100, 0, 0, 0, 0, 1 )
    addShape( 'Square', squareShape, extrudeSettings, 0x0040f0, 150, 100, 0, 0, 0, 0, 1 )
    addShape( 'Heart', heartShape, extrudeSettings, 0xf00000, 60, 100, 0, 0, 0, Math.PI, 1 )
    addShape( 'Circle', circleShape, extrudeSettings, 0x00f000, 120, 250, 0, 0, 0, 0, 1 )
    addShape( 'Fish', fishShape, extrudeSettings, 0x404040, - 60, 200, 0, 0, 0, 0, 1 )
    addShape( 'Smiley', smileyShape, extrudeSettings, 0xf000f0, - 200, 250, 0, 0, 0, Math.PI, 1 )
    addShape( 'Arc', arcShape, extrudeSettings, 0x804000, 150, 0, 0, 0, 0, 0, 1 )
    addShape( 'Spline', splineShape, extrudeSettings, 0x808080, - 50, - 100, 0, 0, 0, 0, 1 )

    const arc = group.getObjectByName( 'Arc' ) as Group
    addLineShape( arc, arcShape.holes[ 0 ], 0x804000, 150, 0, 0, 0, 0, 0, 1 )

    const smiley = group.getObjectByName( 'Smiley' ) as Group
    for ( let i = 0; i < smileyShape.holes.length; i += 1 ) {

      addLineShape( smiley, smileyShape.holes[ i ], 0xf000f0, - 200, 250, 0, 0, 0, Math.PI, 1 )

    }
  }
}

/** A dot per point of `points`, drawn at the points material's size and color. */
function createSprites(points: Points<BufferGeometry, PointsMaterial>) {
  const position = points.geometry.getAttribute( 'position' )

  const material = new PointsNodeMaterial( {
    positionNode: instancedBufferAttribute( new InstancedBufferAttribute( position.array, 3 ) ),
    color: points.material.color,
    size: points.material.size,
    sizeAttenuation: true,
  } )

  const sprites = new Sprite( material )
  sprites.name = 'Sprites'
  sprites.count = position.count
  // A sprite's bounds are one quad at its origin.
  sprites.frustumCulled = false
  sprites.userData.selectable = false

  return sprites
}
